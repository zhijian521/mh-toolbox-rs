/**
 * 捉鬼页「测试文字」的样例。
 *
 * 为什么要有它：真机验证必须开着游戏、把窗口摆前台、等一帧截图，一天做不了几次；
 * 而解析链（`ghost-parse` → `ghost-model` → `map-paint`）全是纯函数，喂一段文字
 * 就能跑完。没有样例时，「改完正则对不对」只能靠回忆上次识别结果。
 *
 * 六条覆盖的不是「好看的例子」，而是**每种会让结果长得不一样的分支**：
 * 范围 / 精确点 / 全角逗号 / 两张图同屏 / 折行与字母误读 / 缺分隔符。
 * 少一条，那条分支就只能等真机出错才发现。
 *
 * 每条都由 `ghost-samples.test.ts` 断言到具体坐标——**样例本身也会坏**：
 * 正则一改，某条样例可能悄悄解析不出来，界面上表现为「点了没反应」，
 * 而那时人正忙着查别的。加样例必须同时加断言。
 *
 * **为什么住在 `views/tools/` 而不是 `services/`**：它是界面上的六枚小签（文案 + 原文），
 * 唯一的消费方是捉鬼页，服务层没有任何代码读它。放 `services/` 会让人以为它是数据源之一，
 * 与 `ghost-maps` 那种「真的去加载资源」的东西混在一起。先例是角色页的
 * `views/characters/mock.ts`——演示数据跟着它的页面走。
 */
export interface GhostTestSample {
    /** 按钮上的短名。**不超过八字**（含「·」与空格），再多面板一行只放得下一枚。 */
    label: string;
    /** 悬停提示：这条样例演示的是哪个分支。 */
    note: string;
    /** 原样粘进输入框的多行文本，**有意保留折行与误读**。 */
    text: string;
}

