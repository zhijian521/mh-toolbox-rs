/** 配色的三个语义档：朱（特技）、赭（套装）、苔（打造附加）。 */
export type GearTone = 'seal' | 'ochre' | 'moss';

/** 装备的一条属性。 */
export interface GearStat {
    label: string;
    value: string;
    /**
     * 方括号里的那个数，如 `物理暴击等级 +8 [+16]` 的 `+16`。
     * 游戏里它是「精炼/灵尘能推到多少」，与前面的值差一档颜色。
     */
    extra?: string;
    /** 打造或镶嵌附加的绿字。 */
    gain?: boolean;
}

/**
 * 装备详情：鼠标停在一格上时浮出来的那张纸。
 *
 * 分六段而不是原来的四段，是因为对着四张真实悬浮图数下来，一件装备至少有
 * 「风味文本 / 条件 / 白字 / 状态 / 特殊 / 制造者」六层——原先只留
 * `base`（白字）与 `gain`（绿字）两段，真实数据里「耐久 191 · 修理失败 1 次」
 * 这种必须显示的状态没地方放。
 */
export interface GearDetail {
    name: string;
    /** 风味描述，游戏里那段斜体的来历。没有就不显示。 */
    flavor?: string;
    /** 类型行：`帽子` / `双剑 · 女` / `灵饰 · 戒指` / `上古玉魄 · 阳`。 */
    kind: string;
    /** 装备条件：`等级 80`、`男`、`五行 木`。合成一行显示。 */
    requires?: string[];
    /** 白字与绿字属性。 */
    stats: GearStat[];
    /** 耐久、修理失败、锻炼/精炼/灵尘等级、镶嵌宝石。 */
    cond?: GearStat[];
    /** 特技 / 特效 / 套装效果。 */
    lines?: { label: string; value: string; tone?: GearTone }[];
    /** 制造者之类。 */
    foot?: string;
}

/** 一格。`detail` 缺席即空位——**空位要占格**，否则「少一件」与「没这一格」分不开。 */
export interface GearSlot {
    slot: GearSlotName;
    /** 格内显示的短名，通常是装备名；太长会省略号截断。 */
    caption?: string;
    detail?: GearDetail;
}

/* ======================================================================
 * 召唤兽
 * ==================================================================== */

/**
 * 一只召唤兽。
 *
 * **信息量大到装不进一格**：属性 9 项 + 资质 6 项 + 寿命/成长/五行 + 技能 12 格 +
 * 内丹 8 格 + 进阶灵性。所以它在卡内是**纵向列表**（一行一只），
 * hover 才浮出「判断值不值」的那一半（资质、成长、五行、寿命）。
 * 技能与内丹只记**名字**，不记图标——图标要进 `public/game/icons/`，
 * 现在没有，而名字本身已经够读。
 */
export interface Pet {
    name: string;
    level: number;
    /** 参战等级：低于人物等级才带得动，是这个号「有没有用」的第一道门槛。 */
    joinLevel: number;
    /** 六项资质。顺序与游戏面板一致。 */
    quality: {
        attack: number;
        defense: number;
        hp: number;
        mp: number;
        speed: number;
        dodge: number;
    };
    /** 寿命。归零就放不出来，是「这只能不能继续用」的硬指标。 */
    life: number;
    /** 成长，如 `1.202`。字符串而不是 number：它是三位小数，转数字会丢末尾的 0。 */
    growth: string;
    /** 五行，如 `火`。 */
    element: string;
    /** 战斗属性，只记上限。 */
    attrs: { label: string; value: string }[];
    /** 已学技能名。 */
    skills: string[];
    /** 内丹名。 */
    innerPills: string[];
    /** 进阶灵性；`undefined` 表示没进阶。 */
    spirit?: number;
}

/* ======================================================================
 * 一个角色
 * ==================================================================== */

export interface CharacterData {
    id: string;
    name: string;
    level: number;
    school: string;
    /** 名字下面那行小字：服务器、称谓、更新时间。 */
    subs: string[];
    /**
     * 属性四组，**顺序即网格顺序**（两行两列，行优先）：
     * 上排 `资源 / 名望`，下排 `战斗 / 加点`（用户 2026-11-02 定）。
     *
     * 不是「两列、每列两组」：名望只有 3 行而资源有 6 行，按列排时下排两组会被
     * 上一组的短拖着错位——左列「战斗」比右列「加点」高出一截。按行排，上下两排
     * 各自顶对齐，四组的位置只由顺序决定，返回去看的是同一张表。
     */
    attrGroups: AttrGroup[];
    /** 经验单独一行（带进度条），不占 `attrGroups` 的位置。 */
    experience: ExpRow;
    attrFoot: string;
    skills: SkillRow[];
    skillFoot: string;
    /** 辅助技能：生活 + 剧情，两类合在一页格子里。 */
    assists: AssistSkill[];
    assistFoot: string;
    /** 两组：角色自身修炼、召唤兽控制修炼。 */
    trainings: TrainingGroup[];
    trainingFoot: string;
    gear: GearSlot[];
    gearMeta: { special: string; suit: string };
    pets: Pet[];
    petFoot: string;
}
