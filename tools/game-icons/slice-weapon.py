def late_items(group):
    """该组的名字表。双巨斧按乾/坤拆开（**17 档全要，含 160 的「非天」**）。"""
    if group.startswith('双巨斧'):
        side = '乾' if group.endswith('乾') else '坤'
        return [(n.replace('（乾坤）', '（%s）' % side), lv, hi) for n, lv, hi in ROWS['双巨斧']]
    return ROWS[group]


def late_fid(group, lv, dup=''):
    """文件名。双巨斧两组共用 `shuangjufu`，用 `qian`/`kun` 段区分乾、坤——
    不能再借 `a`/`b` 后缀，因为 90 级与 120 级各有三款，那一段后缀已经用掉了。"""
    if group.startswith('双巨斧'):
        side = 'qian' if group.endswith('乾') else 'kun'
        return 'weapon-shuangjufu-{}-{:03d}{}'.format(side, lv, dup)
    return 'weapon-{}-{:03d}{}'.format(KEY[group], lv, dup)


GROUP = 17          # 每种武器的档数
CARD = np.array([240, 212, 176])   # 格子底（比防具页的米黄略暗）
COLS = [(154, 247), (278, 371), (402, 495)]   # 三列格子（各 94 宽，由竖向间隙量出）
CELL, STEP = 94, 110               # 格子高、行距
INSET = 2                          # 格边内缩：与装备一致（裁 90 → 96）
TOP_MIN, TOP_MAX = 488, 960        # 下拉框底 / 面板底，越界的行不完整


def rows_with_names():
    """把 ROWS 摊平成「全局行号 → (种类, 名称, level, level_hi)」。"""
    out = []
    for kind, items in ROWS.items():
        for name, lv, hi in items:
            out.append((kind, name, lv, hi))
    return out


def gap_segments(a):
    """找「整行三格都是淡色差」的间隙段：格子之间是 16px 的浅色缝。"""
    d = np.abs(a - CARD).sum(axis=2)
    faint = (d > 8) & (d < 55)
    ratio = np.array([faint[y, COLS[0][0]:COLS[-1][1] + 1].mean() for y in range(430, 1000)])
    segs = []
    for y in range(430, 1000):
        if ratio[y - 430] > 0.85:
            if segs and y - segs[-1][1] <= 1:
                segs[-1][1] = y
            else:
                segs.append([y, y])
    return [(s, e) for s, e in segs]


def grid_tops(a):
    """用间隙段求本页的行相位，再按 STEP 生成格子顶。

    为什么不用「内容投影」：图标贴格子顶时内容起点就是格子顶，再减 2px 会跑到格子外，
    裁进来的是上一格的下边框；图标不贴顶时又会少 8px。两种错法混在一起，就是
    「有的上面多一条边、有的被切掉一截」。间隙的位置与图标无关，稳得多。
    """
    votes = {}
    for y0, y1 in gap_segments(a):
        if 10 <= y1 - y0 + 1 <= 24:      # 完整间隙才投票，被面板截断的不算
            t = (y1 + 1) % STEP
            votes[t] = votes.get(t, 0) + 1
    if not votes:
        return []
    ph = max(votes.items(), key=lambda kv: kv[1])[0]
    return [y for y in range(430, 1000)
            if y % STEP == ph and TOP_MIN <= y and y + CELL <= TOP_MAX]


def has_band(im):
    """裁出来的图，顶边或底边是不是一条「格子之间的缝」。

    为什么必须挡：列表最底那一行被面板下边缘切掉，底边兜到的是面板边界，
    拼图时会在四格交汇处横着拉出一条亮带（用户实测指出）。这种格子宁可不要，
    让合并流程去别的页取同一行完整的那一份。
    """
    d = np.abs(np.asarray(im.convert('RGB')).astype(int) - CARD).sum(axis=2)
    for seg in (d[0], d[1], d[-2], d[-1]):
        if ((seg >= 8) & (seg <= 55)).mean() > 0.85 and float(seg.std()) < 26:
            return True
    return False


def cut(a, im, y0, ci):
    """切一格并缩放到 96×96；空格返回 None。

    **固定取景**：按格子边内缩 INSET，不追图标包围盒。追包围盒有两个后遗症，
    都被人眼抓到过：图标被拉到贴边（看着像被裁），以及贴顶的图标把框顶推到格子外、
    带进一条更亮的间隙。留白多少由游戏原图决定，别替它决定。
    """
    x0, x1 = COLS[ci]
    blk = a[y0:y0 + CELL, x0:x1 + 1]
    if (np.abs(blk - CARD).sum(axis=2) <= 45).mean() > 0.9:   # 空格
        return None
    # 内缩 2 → 90×90 → 96×96：与 slice-gear.py 完全同规格。
    # 内缩不能更大：卡片四角的卷云纹是「四格拼成完整图案」的那四分之一，
    # 内缩 4 就会把云纹的角切掉，拼在一起时缺一瓣（用户实测反馈）。
    # 先按标准位置取；若底边兜到了面板边界（列表最底那一行会这样），
    # 就整体上移再取——卡片 94 高只取 90，有 4~6px 余量。个别件因此比其他图上移
    # 几个像素，但总比缺件或带一条亮边强。
    for k in (0, 2, 4, 6, 8):
        top = y0 + INSET - k
        bot = y0 + CELL - INSET - k
        if top < 0:
            break
        img = im.crop((x0 + INSET, top, x1 - INSET + 1, bot)).resize((96, 96), Image.LANCZOS)
        if not has_band(img):
            return img
    return None


def page_cells(path, top_min, top_max):
    """按本页自己的上下界切出全部格子（不判 60 级，顺序是行优先、三列）。"""
    global TOP_MIN, TOP_MAX
    old = TOP_MIN, TOP_MAX
    TOP_MIN, TOP_MAX = top_min, top_max
    try:
        im = Image.open(path).convert('RGB')
        a = np.asarray(im).astype(int)
        return [cut(a, im, y0, ci) for y0 in grid_tops(a) for ci in range(len(COLS))]
    finally:
        TOP_MIN, TOP_MAX = old


def main() -> int:
    check = '--check' in sys.argv
    flat = rows_with_names()
    if len(flat) != 340:
        raise SystemExit('名称表应为 340 行（20 种 × 17 档），实际 {}'.format(len(flat)))

    groups = OrderedDict()
    taken = set()          # 同一全局行只取一张：相邻截图有 0~3 行重叠，不挡会切出重复
    for page, fname in enumerate(SCREENSHOTS, start=1):
        path = SRC / fname
        if not path.exists():
            raise SystemExit('找不到截图：{}'.format(path))
        im = Image.open(path).convert('RGB')
        a = np.asarray(im).astype(int)
        offset = OFFSETS.get(page)
        if offset is None:
            continue
        j = 0
        for y0 in grid_tops(a):
            for ci in range(len(COLS)):
                seq = offset + j
                j += 1
                if not (0 <= seq < len(flat)):
                    continue
                kind, name, lv, hi = flat[seq]
                if lv < 60:          # 60 级以下不要
                    continue
                if seq in taken:
                    continue
                img = cut(a, im, y0, ci)
                if img is None:
                    continue
                taken.add(seq)
                groups.setdefault(kind, []).append((seq, name, lv, hi, img))

    # ---- 后五种（巨剑 / 灯笼 / 伞 / 双巨斧乾·坤 / 棍）
    # 这批截图是乱序的，不能靠「第几页 = 列表第几段」推，只能按 LATE_PAGES 里
    # 写死的「页 + 起始档」切。切图本身与上面完全同规格（同一个 cut()）。
    late = OrderedDict()
    for slot, group, start, tmin, tmax in LATE_PAGES:
        page, src = slot
        fname = SCREENSHOTS[page - 1] if src == 'S' else LATE_SHOTS[page - 1]
        path = SRC / fname
        if not path.exists():
            raise SystemExit('找不到截图：{}'.format(path))
        items = late_items(group)
        bucket = late.setdefault(group, OrderedDict())
        for j, img in enumerate(page_cells(path, tmin, tmax)):
            idx = start + j
            if img is None or not (1 <= idx <= len(items)) or idx in bucket:
                continue
            name, lv, hi = items[idx - 1]
            if lv >= 60:                          # 同一档只取先遇到的那张
                bucket[idx] = (name, lv, hi, img)

    # 切到的档必须覆盖名字表里 lv >= 60 的**每一档**。
    # 少一档不会报错，只会让「后面还有几档」这件事消失：轻则清单少一条，重则
    # 后一档的名字配到前一档的图上，而画面上「看起来都像斧头」。双巨斧就栽在这里——
    # 160 的「非天」因为截图没覆盖到最底那一格，被误记成「客户端没有这个造型」。
    lacking = []
    for group, bucket in late.items():
        items = late_items(group)
        need = [i for i, (_, lv, _) in enumerate(items, 1) if lv >= 60]
        lack = [items[i - 1][0] for i in need if i not in bucket]
        if lack:
            lacking.append('{}：{}'.format(group, '、'.join(lack)))
    if lacking:
        raise SystemExit(
            '这些档没切到（截图没覆盖到）——' + '；'.join(lacking) +
            '\n补那张截图后再跑。图片已改从客户端导入时，也可以直接跑 '
            'tools/game-icons/import-slot-icons.py 覆写。')

    out_dir = ROOT / 'public/game/icons/weapon'
    manifest = {'generated-by': 'tools/game-icons/slice-weapon.py', 'groups': {}}
    total = 0
    if not check:
        # 整目录改名备份再重建：逐文件 unlink 在本机被 safe-delete 拦，会中途断掉，
        # 只剩一半文件（实测只写出 113/165）。
        if out_dir.is_dir():
            bak = ROOT / '.runtime' / 'weapon-bak'
            if bak.is_dir():
                shutil.rmtree(bak, ignore_errors=True)
            out_dir.rename(bak)
        out_dir.mkdir(parents=True, exist_ok=True)
    for kind, items in groups.items():
        seen = {}
        entries = []
        # 按全局序号排：同一等级可能有多款（b/c 后缀就按这个顺序发），
        # 按收集顺序发会因「某页格子被拒收、改从别页取」而把 b/c 对调。
        for seq, name, lv, hi, img in sorted(items, key=lambda t: t[0]):
            n = seen.get(lv, 0)
            seen[lv] = n + 1
            fid = 'weapon-{}-{:03d}{}'.format(KEY[kind], lv, '' if n == 0 else chr(ord('a') + n))
            if not check:
                # 有损 92、不带 alpha：这批图标本来就有卡片底
                img.save(out_dir / (fid + '.webp'), 'WEBP', quality=92, method=6)
            entries.append({'id': fid, 'img': fid + '.webp', 'name': name, 'level': lv, 'level_hi': hi})
        manifest['groups'][kind] = entries
        total += len(entries)
        print('{:4s} {:2d} 件'.format(kind, len(entries)))

    # 后五种的落盘与清单（命名规则不同：双巨斧靠 a/b 区分乾、坤）
    for group, bucket in late.items():
        entries = []
        used = {}
        for idx, (name, lv, hi, img) in sorted(bucket.items()):
            n = used.get(lv, 0)
            used[lv] = n + 1
            dup = '' if n == 0 else chr(ord('a') + n)    # 90/120 级的三款：b、c
            fid = late_fid(group, lv, dup)
            if not check:
                img.save(out_dir / (fid + '.webp'), 'WEBP', quality=92, method=6)
            entries.append({'id': fid, 'img': fid + '.webp',
                            'name': name, 'level': lv, 'level_hi': hi})
        manifest['groups'][group] = entries
        total += len(entries)
        print('{:4s} {:2d} 件（后补）'.format(group, len(entries)))

    # 清单按官网的种类顺序排，双巨斧拆成乾、坤两组插在原位置
    ordered = OrderedDict()
    for kind in ROWS:
        if kind == '双巨斧':
            for g in ('双巨斧·乾', '双巨斧·坤'):
                if g in manifest['groups']:
                    ordered[g] = manifest['groups'][g]
        elif kind in manifest['groups']:
            ordered[kind] = manifest['groups'][kind]
    for g, v in manifest['groups'].items():
        ordered.setdefault(g, v)
    manifest['groups'] = ordered

    if not check:
        with open(ROOT / 'public/game/data/weapon-icons.json', 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(json.dumps(manifest, ensure_ascii=False, indent=4) + '\n')
    print('合计', total, '件' + ('（check，未写文件）' if check else ''))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
